// Domain Entity: DataEntry
class DataEntry {
  constructor(id, dataType, category, clientId, data, createdAt) {
    this.id = id;
    this.dataType = dataType;
    this.category = category;
    this.clientId = clientId;
    this.data = data;
    this.createdAt = createdAt;
  }

  static create(dataType, category, clientId, data) {
    if (!data) {
      throw new Error('Data cannot be null or undefined');
    }

    if (typeof data !== 'object') {
      throw new Error('Data must be an object');
    }

    if (!clientId) {
      throw new Error('Client ID is required for tracking');
    }

    return new DataEntry(
      null, // ID will be generated by infrastructure
      dataType || 'general',
      category || 'uncategorized',
      clientId,
      data,
      new Date()
    );
  }

  validate() {
    if (!this.dataType) {
      throw new Error('DataType is required');
    }

    if (!this.category) {
      throw new Error('Category is required');
    }

    if (!this.clientId) {
      throw new Error('Client ID is required');
    }

    if (!this.data) {
      throw new Error('Data is required');
    }

    return true;
  }

  toJSON() {
    return {
      id: this.id,
      dataType: this.dataType,
      category: this.category,
      clientId: this.clientId,
      data: this.data,
      createdAt: this.createdAt
    };
  }
}

module.exports = DataEntry;
